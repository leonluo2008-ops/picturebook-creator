def main():
    path = sys.argv[1]
    check_only = "--check" in sys.argv
    text = io.open(path, encoding="utf-8").read()
    total = 0
    rows = []
    for rid, old, new, expect in REPLACEMENTS:
        n = text.count(old)
        ok = (n == expect)
        rows.append((rid, n, expect, ok))
        if ok:
            text = text.replace(old, new)
        total += 1
    bad = [r for r in rows if not r[3]]
    for rid, n, expect, ok in rows:
        print("%-7s 命中 %d 次（预期 %d）%s" % (rid, n, expect, "" if ok else "  <<< 不匹配，未改"))
    if bad:
        print("\n[中止] 有 %d 处未按预期命中，**未写盘**。请先核对原文。" % len(bad))
        return 2
    if check_only:
        print("\n[check] 全部命中，将改动 %d 处（未写盘）" % total)
        return 0
    io.open(path, "w", encoding="utf-8", newline="").write(text)
    print("\n[完成] 已改写 %d 处: %s" % (total, path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
