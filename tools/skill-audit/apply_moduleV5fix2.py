def main():
    path = sys.argv[1]
    check_only = "--check" in sys.argv
    text = io.open(path, encoding="utf-8").read()
    rows = []
    for rid, old, new, expect in REPLACEMENTS:
        n = text.count(old)
        rows.append((rid, n, expect))
        if n == expect:
            text = text.replace(old, new)
    bad = [r for r in rows if r[1] != r[2]]
    for rid, n, expect in rows:
        print("%-20s 命中 %d（预期 %d）%s" % (rid, n, expect, "" if n == expect else "  <<< 不匹配"))
    if bad:
        print("\n[中止] %d 处未命中，未写盘。" % len(bad))
        return 2
    if check_only:
        print("\n[check] 全部命中（%d 处），未写盘" % len(REPLACEMENTS))
        return 0
    io.open(path, "w", encoding="utf-8", newline="").write(text)
    print("\n[完成] 已改写 %d 处" % len(REPLACEMENTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
