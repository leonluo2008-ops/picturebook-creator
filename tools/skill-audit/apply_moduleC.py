# -*- coding: utf-8 -*-
"""模块 C（台账与状态机）改动。

依据（2026-11-21 实测）：
- 台账 schema 状态 select 共 8 项
- 全库 639 行分布：备选264/弃用161/已制作128(其中120无交付文件)/待制作72/已筛查12/待生图2/**修改中0/已生图0**
- 结论：`已制作`≠已交付（看交付文件列）；`修改中`/`已生图` 零历史样本，需按新规则首次启用

用法: python apply_moduleC.py <SKILL.md> [--check]
"""
import io
import sys

OLD_STATUS = (
    "- **台账「状态」列(实测选项)**:`已筛查 / 待制作 / 待生图 / 已制作 / 修改中 / 备选 / 弃用`"
    "(以当次 query 库 schema 为准,选项可能增减)。`已筛查` = 选题已过筛查、还没动笔:"
    "派到这个词就按全新 L1→L5 做,别当成 `已制作` 去走存量重整。"
    "`修改中` = 甲方或审计打回、待改的书(用户 2026-10-27 新增的状态):"
    "改完**仍留 `修改中`**等复审,不自行推 `待生图`——推不推由用户或复审环节决定。"
)

NEW_STATUS = """- **台账「状态」列（2026-11-21 实测 schema 共 8 项）**：`已筛查 / 备选 / 待制作 / 待生图 / 已制作 / 已生图 / 修改中 / 弃用`（以当次 fetch 的 schema 为准，选项可能增减）。
  - **实测分布**（全库 639 行）：备选 264 / 弃用 161 / 已制作 128（其中 **120 本无交付文件**）/ 待制作 72 / 已筛查 12 / 待生图 2 / **修改中 0 / 已生图 0**。后两个是新增状态、**零历史样本**，按本表规则首次启用，别假装有先例。
  - **`已制作` ≠ 已交付**：判断「这本书交付过没有」看「交付文件」列，不看状态。

| 状态 | 含义 | 谁能推进 / 何时 | 推进前必须做完 |
|---|---|---|---|
| 备选 | 台账已有、未筛查 | 筛查环节决定 | — |
| 已筛查 | 选题过筛、没动笔 | 派到即开全新 L1→L5 | 不要当 `已制作` 走存量重整 |
| 待制作 | 已排进制作计划、未开工 | 开工即走 L1→L5 | — |
| 待生图 | L4 已确认并归档，等出图 | **agent 自动**：归档 + 回读校验通过后 | 归档写入 + 回读逐项校验 |
| 已生图 | 图已出，**且交付包已挂「交付文件」** | **agent 自动**：交付回读通过后 | 打包 + 上传 + 独立回读（缺一不可，不能只看本地有 zip） |
| 修改中 | 审核/甲方打回，待改 | 收到意见即置；改完**仍留此态**等复审 | 按「改写模式」归层修改 + 三道门全绿 |
| 弃用 | 终态，不再做 | 仅所有者决定 | — |
| 已制作 | **历史状态**：已有产出（未必生图/交付） | 不再主动写入 | 存量书走「存量重整」或「改写模式」，先查交付文件列判断实际进度 |

> **状态自动推进只有两个动作**：①归档完成 → `待生图`；②交付回读通过 → `已生图`。
> 其余流转（备选/已筛查/待制作/修改中/弃用）一律由人或复审环节决定，**agent 不得自行推进**。"""

OLD_RULE = (
    "- 归档成功后状态唯一推进动作:该行「状态」置为「待生图」并回读验证;"
    "除此之外状态列不动(其余状态流转归排产流水线管)。"
)
NEW_RULE = (
    "- 归档成功后状态推进动作:该行「状态」置为「待生图」并回读验证。"
    "**agent 允许自动改状态的情形只有两个**：归档完成→`待生图`、交付回读通过→`已生图`；"
    "除此之外状态列一律不动（其余流转归排产流水线与复审管）。"
)

REPLACEMENTS = [
    ("C1-状态表", OLD_STATUS, NEW_STATUS, 1),
    ("C2-铁律状态推进", OLD_RULE, NEW_RULE, 1),
]


def main():
    path = sys.argv[1]
    check_only = "--check" in sys.argv
    text = io.open(path, encoding="utf-8").read()
    rows = []
    for rid, old, new, expect in REPLACEMENTS:
        n = text.count(old)
        rows.append((rid, n, expect))
        if n == expect:
            text = text.replace(old, new)
    bad = [r for r in rows if r[1] != r[2]]
    for rid, n, expect in rows:
        print("%-18s 命中 %d（预期 %d）%s" % (rid, n, expect, "" if n == expect else "  <<< 不匹配"))
    if bad:
        print("[中止] 未按预期命中，未写盘。")
        return 2
    if check_only:
        print("[check] 全部命中（未写盘）")
        return 0
    io.open(path, "w", encoding="utf-8", newline="").write(text)
    print("[完成] 已改写 %d 处" % len(REPLACEMENTS))
    return 0


if __name__ == "__main__":
    sys.exit(main())
